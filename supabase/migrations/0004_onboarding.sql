-- Kullanıcıya özel konu düzenleme (ad değiştirme, gizleme, yeni konu) + ilk giriş karşılama bayrağı.
-- Supabase SQL Editor'da bir kez çalıştırın (tekrar çalıştırılabilir). Önce 0003_plan.sql çalışmış olmalı.

-- Özel konular ortak "topics" tablosunda olmadığı için ilerleme tablolarındaki yabancı anahtarlar kalkar.
alter table public.progress drop constraint if exists progress_topic_id_fkey;
alter table public.daily_plan drop constraint if exists daily_plan_topic_id_fkey;
alter table public.study_log drop constraint if exists study_log_topic_id_fkey;

create table if not exists public.custom_topics (
  id int generated by default as identity (start with 10000) primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  ders text not null,
  bolum text not null default '',
  konu text not null check (char_length(konu) between 1 and 200),
  created_at timestamptz not null default now()
);

create table if not exists public.topic_edits (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  topic_id int not null,
  konu text check (konu is null or char_length(konu) between 1 and 200),
  hidden boolean not null default false,
  primary key (user_id, topic_id)
);

alter table public.plan_settings add column if not exists onboarded boolean not null default false;

alter table public.custom_topics enable row level security;
alter table public.topic_edits enable row level security;

drop policy if exists custom_topics_own on public.custom_topics;
create policy custom_topics_own on public.custom_topics for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists topic_edits_own on public.topic_edits;
create policy topic_edits_own on public.topic_edits for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
